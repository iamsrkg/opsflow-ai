-- The tables behind the JPA entities. Hibernate only validates against this (ddl-auto=validate);
-- it never changes the schema in the PostgreSQL profile.

create table ai_investigations (
    confidence_score float(53),
    requires_approval boolean,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    request_id bigint not null,
    updated_at timestamp(6) not null,
    evidence_json TEXT,
    investigated_by varchar(255) not null,
    likely_cause TEXT,
    recommended_action varchar(255),
    relevant_runbook_title varchar(255),
    summary TEXT,
    primary key (id)
);

create table approval_requests (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    request_id bigint not null,
    updated_at timestamp(6) not null,
    action_type varchar(255) not null,
    approved_by varchar(255),
    payload_json TEXT,
    proposed_by varchar(255) not null,
    reasoning TEXT,
    status varchar(255) not null check (status in ('PENDING','APPROVED','REJECTED')),
    primary key (id)
);

create table audit_events (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    request_id bigint,
    updated_at timestamp(6) not null,
    action varchar(255),
    correlation_id varchar(255),
    metadata_json TEXT,
    result varchar(255) not null,
    what varchar(255) not null,
    who varchar(255) not null,
    why TEXT,
    primary key (id)
);

create table knowledge_chunks (
    chunk_index integer not null,
    created_at timestamp(6) not null,
    document_id bigint not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    text TEXT not null,
    vector_embedding TEXT,
    primary key (id)
);

create table knowledge_documents (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    category varchar(255) not null,
    content TEXT not null,
    tags varchar(255),
    title varchar(255) not null,
    primary key (id)
);

create table notifications (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    message varchar(500) not null,
    aggregate_id varchar(255),
    correlation_id varchar(255),
    event_id varchar(255) not null,
    event_type varchar(255) not null,
    recipient varchar(255) not null,
    primary key (id)
);

create table outbox_events (
    attempts integer not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    processed_at timestamp(6),
    updated_at timestamp(6) not null,
    aggregate_id varchar(255) not null,
    aggregate_type varchar(255) not null,
    correlation_id varchar(255),
    error_message varchar(255),
    event_id varchar(255) not null unique,
    event_type varchar(255) not null,
    payload_json TEXT not null,
    status varchar(255) not null check (status in ('PENDING','PUBLISHED','FAILED')),
    primary key (id)
);

create table processed_events (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    consumer_group varchar(255) not null,
    event_id varchar(255) not null,
    event_type varchar(255),
    primary key (id),
    unique (event_id, consumer_group)
);

create table request_history (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    request_id bigint not null,
    updated_at timestamp(6) not null,
    changed_by varchar(255) not null,
    comment TEXT,
    new_status varchar(255) not null check (new_status in ('CREATED','CLASSIFIED','ASSIGNED','INVESTIGATING','PENDING_APPROVAL','ACTION_IN_PROGRESS','RESOLVED','CLOSED','ESCALATED','WAITING_FOR_USER')),
    previous_status varchar(255) check (previous_status in ('CREATED','CLASSIFIED','ASSIGNED','INVESTIGATING','PENDING_APPROVAL','ACTION_IN_PROGRESS','RESOLVED','CLOSED','ESCALATED','WAITING_FOR_USER')),
    primary key (id)
);

create table requests (
    confidence_score float(53),
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    resolved_at timestamp(6),
    updated_at timestamp(6) not null,
    version bigint,
    assigned_to varchar(255),
    category varchar(255) not null check (category in ('PAYMENT','ORDER','BOOKING','DELIVERY','ACCOUNT','TECHNICAL','SERVICE','ACCESS','OTHER')),
    classification_summary TEXT,
    created_by varchar(255) not null,
    description TEXT not null,
    external_reference varchar(255) not null unique,
    priority varchar(255) not null check (priority in ('LOW','MEDIUM','HIGH','CRITICAL')),
    status varchar(255) not null check (status in ('CREATED','CLASSIFIED','ASSIGNED','INVESTIGATING','PENDING_APPROVAL','ACTION_IN_PROGRESS','RESOLVED','CLOSED','ESCALATED','WAITING_FOR_USER')),
    title varchar(255) not null,
    primary key (id)
);

create table users (
    enabled boolean not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    email varchar(255) not null unique,
    full_name varchar(255) not null,
    password varchar(255) not null,
    role varchar(255) not null check (role in ('ADMIN','MANAGER','AGENT','OPERATOR','VIEWER')),
    username varchar(255) not null unique,
    primary key (id)
);

create index idx_ai_req_id 
   on ai_investigations (request_id);

create index idx_audit_req_id 
   on audit_events (request_id);

create index idx_audit_who 
   on audit_events (who);

create index idx_audit_corr_id 
   on audit_events (correlation_id);

create index idx_chunk_doc_id 
   on knowledge_chunks (document_id);

create index idx_notification_recipient 
   on notifications (recipient);

create index idx_outbox_status 
   on outbox_events (status);

create index idx_outbox_created 
   on outbox_events (created_at);

create index idx_req_external_ref 
   on requests (external_reference);

create index idx_req_status 
   on requests (status);

create index idx_req_category 
   on requests (category);

create index idx_req_priority 
   on requests (priority);
